def problems(s):
    """回傳這段文字的問題清單（只看含中文的文字）。"""
    if not CJK.search(s):
        return []
    out = []
    if DASH.search(s):
        out.append("破折號")
    bad = sorted({c for c in s if c in SIMP})
    if bad:
        out.append("簡體字 " + "".join(bad))
    return out
